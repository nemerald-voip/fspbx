import { mkdir, readdir, readFile, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createProcessor } from '@mdx-js/mdx';

const repository = 'nemerald-voip/fspbx';
const outputDirectory = fileURLToPath(new URL('../blog/releases/', import.meta.url));
const generatedMarker = '<!-- Generated by scripts/sync-releases.mjs. Edit the GitHub release. -->';
const markdown = createProcessor({ format: 'md' });
const emptyReleaseText = 'See the GitHub release for details.';

function inlineText(node) {
    if (node.type === 'text' || node.type === 'inlineCode') return node.value;
    if (node.type === 'break') return ' ';
    if (node.type === 'html' || node.type === 'image' || node.type === 'imageReference') return '';
    return (node.children ?? []).map(inlineText).join('');
}

function openingText(nodes) {
    for (const node of nodes) {
        let text = '';
        if (node.type === 'paragraph') {
            // Some older releases use headings without a space, such as ##What's new.
            text = inlineText(node).replace(/^#{1,6}[^\n]*(?:\n|$)/gm, '');
        } else if (node.type === 'list') {
            text = node.children.map(item => openingText(item.children))
                .filter(Boolean).slice(0, 3).join('; ');
        } else if (node.type === 'blockquote') {
            text = openingText(node.children);
        }
        text = text.replace(/\s+/g, ' ').trim();
        if (text) return text;
    }
    return '';
}

export function createReleasePreview(body) {
    const text = openingText(markdown.parse(body ?? '').children) || emptyReleaseText;
    if (text.length <= 300) return text;
    const shortened = text.slice(0, 299);
    const wordEnd = shortened.lastIndexOf(' ');
    return `${(wordEnd > 0 ? shortened.slice(0, wordEnd) : shortened).trimEnd()}…`;
}

export async function fetchReleases({ token = process.env.GITHUB_TOKEN, fetchImpl = fetch } = {}) {
    const releases = new Map();
    for (let page = 1; ; page++) {
        const response = await fetchImpl(
            `https://api.github.com/repos/${repository}/releases?per_page=100&page=${page}`,
            {
                headers: {
                    Accept: 'application/vnd.github+json',
                    'X-GitHub-Api-Version': '2022-11-28',
                    ...(token ? { Authorization: `Bearer ${token}` } : {}),
                },
                signal: AbortSignal.timeout(30_000),
            },
        );
        if (!response.ok) {
            throw new Error(`GitHub releases request failed (HTTP ${response.status}, page ${page}).`);
        }
        const batch = await response.json();
        if (!Array.isArray(batch)) {
            throw new Error('GitHub releases response must be an array.');
        }
        for (const release of batch) {
            if (!release || !Number.isSafeInteger(release.id) || release.id <= 0
                || typeof release.draft !== 'boolean' || typeof release.prerelease !== 'boolean') {
                throw new Error('GitHub returned an invalid release record.');
            }
            releases.set(release.id, release);
        }
        if (batch.length < 100) return [...releases.values()];
    }
}

export function renderRelease(release) {
    if (typeof release.tag_name !== 'string' || !release.tag_name.trim()
        || typeof release.published_at !== 'string' || !Number.isFinite(Date.parse(release.published_at))
        || (release.body != null && typeof release.body !== 'string')) {
        throw new Error(`Invalid metadata for release ${release.id}.`);
    }
    const tag = release.tag_name;
    const title = release.name?.trim() || `FS PBX ${tag}`;
    const releaseUrl = `https://github.com/${repository}/releases/tag/${encodeURIComponent(tag)}`;
    const preview = createReleasePreview(release.body);
    return [
        '---',
        `title: ${JSON.stringify(title)}`,
        // A YAML timestamp becomes a Date. Docusaurus 3.9 appends "Z" to
        // string dates, which would invalidate GitHub's already-UTC timestamp.
        `date: ${new Date(release.published_at).toISOString()}`,
        `slug: ${JSON.stringify(`release-${encodeURIComponent(tag)}`)}`,
        `description: ${JSON.stringify(preview)}`,
        `release_preview: ${JSON.stringify(preview)}`,
        'tags: [release]',
        // Release notes are GitHub Markdown, not executable MDX expressions.
        'mdx:',
        '  format: md',
        '---',
        generatedMarker,
        '',
        `[View this release on GitHub](${releaseUrl})`,
        '',
        '<!-- truncate -->',
        '',
        release.body?.trim() || emptyReleaseText,
        '',
    ].join('\n');
}

export async function syncReleases({ directory = outputDirectory, ...fetchOptions } = {}) {
    // Fetch and validate the whole snapshot before touching existing pages.
    // A failed request must fail the build rather than publish a partial history.
    const releases = await fetchReleases(fetchOptions);
    const posts = new Map(releases
        .filter(release => !release.draft && !release.prerelease)
        .map(release => [`${release.id}.md`, renderRelease(release)]));

    await mkdir(directory, { recursive: true });
    const generatedFiles = [];
    for (const entry of await readdir(directory, { withFileTypes: true })) {
        if (!entry.isFile() || !/^\d+\.md$/.test(entry.name)) continue;
        const content = await readFile(path.join(directory, entry.name), 'utf8');
        if (content.includes(generatedMarker)) {
            generatedFiles.push(entry.name);
        } else if (posts.has(entry.name)) {
            throw new Error(`Refusing to overwrite a manual blog post: ${entry.name}`);
        }
    }
    for (const [filename, content] of posts) {
        await writeFile(path.join(directory, filename), content);
    }
    // Remove only our own pages for deleted, unpublished, or prerelease entries.
    for (const filename of generatedFiles) {
        if (!posts.has(filename)) await unlink(path.join(directory, filename));
    }
    return posts.size;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    syncReleases()
        .then(count => console.log(`Generated ${count} release posts in documentation/blog/releases/.`))
        .catch(error => {
            console.error(`Release sync failed: ${error.message}`);
            process.exitCode = 1;
        });
}
