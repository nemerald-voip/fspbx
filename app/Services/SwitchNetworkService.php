<?php

namespace App\Services;

use App\Models\SwitchVariable;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Process;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;
use Throwable;

class SwitchNetworkService
{
    public const NAMES = ['local_ip_v4', 'external_sip_ip', 'external_rtp_ip'];

    public function __construct(private readonly SwitchVariableService $variables)
    {
    }

    public function state(): array
    {
        $runtime = $this->runtime();
        $interfaces = $this->interfaces();
        $rows = $this->rows($runtime['hostname']);
        $saved = [];
        foreach (self::NAMES as $name) {
            $matches = $rows->where('var_name', $name)->where('var_enabled', 'true');
            // Suggest the specific row, but the review still lists every applicable definition.
            $row = $matches->firstWhere('var_hostname', $runtime['hostname']) ?? $matches->first();
            $saved[$name] = $row?->var_value;
        }
        $local = $saved['local_ip_v4'] ?: ($runtime['values']['local_ip_v4'] ?? null);
        if (! filter_var($local, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4)) {
            $local = null;
        }
        $external = $saved['external_sip_ip'];
        $media = $saved['external_rtp_ip'];
        $nat = filled($external) && $external !== '$${local_ip_v4}' && $external !== $local;

        return [
            'hostname' => $runtime['hostname'],
            'interfaces' => $interfaces,
            'loaded' => $runtime['values'],
            'item' => [
                'hostname' => $runtime['hostname'],
                'layout' => $nat ? 'nat' : ($this->publicIp((string) $local) ? 'direct' : 'private'),
                'local_ip' => $local,
                'public_ip' => $nat && filter_var($external, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) ? $external : null,
                'separate_media' => $nat && filled($media) && $media !== $external,
                'media_ip' => filter_var($media, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) ? $media : null,
            ],
        ];
    }

    public function preview(array $data): array
    {
        $runtime = $this->validateNetwork($data);
        return $this->review($data, $runtime['hostname'], $this->rows($runtime['hostname']));
    }

    public function apply(array $data): array
    {
        // Identify the responding node and check its interface again. A shared web address
        // must not apply a review generated by another node, even with a replicated DB/key.
        $runtime = $this->validateNetwork($data);
        $hostname = $runtime['hostname'];

        return Cache::lock('switch-network-setup:'.hash('sha256', $hostname), 30)->block(5, function () use ($data, $hostname) {
            DB::transaction(function () use ($data, $hostname) {
                // Also serialize against manual inserts of duplicate names, which are not
                // covered by row locks when no definition exists yet.
                if (DB::getDriverName() === 'pgsql') {
                    DB::statement('LOCK TABLE v_vars IN SHARE ROW EXCLUSIVE MODE');
                }
                $rows = $this->rows($hostname, true);
                $review = $this->review($data, $hostname, $rows);
                if (! hash_equals($review['review_token'], (string) ($data['review_token'] ?? ''))) {
                    throw ValidationException::withMessages([
                        'review_token' => [__('Network settings changed. Review the changes again before applying.')],
                    ]);
                }

                foreach ($review['changes'] as $change) {
                    $row = $change['id'] ? $rows->firstWhere('var_uuid', $change['id']) : new SwitchVariable();
                    if ($change['action'] === 'disable') {
                        $row->update(['var_enabled' => 'false']);
                        continue;
                    }

                    $row->forceFill([
                        'var_uuid' => $row->var_uuid ?: (string) Str::uuid(),
                        'var_name' => $change['name'],
                        'var_value' => $change['value'],
                        'var_category' => 'IP Address',
                        'var_command' => 'set',
                        'var_order' => $change['order'],
                        'var_hostname' => $hostname,
                        'var_enabled' => 'true',
                    ])->save();
                }
            });

            // Persisted configuration must survive an offline switch or a failed file write.
            try {
                $this->variables->syncAndReloadXml($hostname);
                return ['saved' => true, 'synchronized' => true, 'hostname' => $hostname, 'errors' => []];
            } catch (ValidationException $exception) {
                return ['saved' => true, 'synchronized' => false, 'hostname' => $hostname, 'errors' => $exception->errors()];
            }
        });
    }

    private function validateNetwork(array $data): array
    {
        $runtime = $this->runtime();
        if ($runtime['hostname'] !== $data['hostname']) {
            throw ValidationException::withMessages([
                'hostname' => [__('This request reached a different server. Open this server directly and refresh Network Setup.')],
            ]);
        }
        if (! in_array($data['local_ip'], array_column($this->interfaces(), 'address'), true)) {
            throw ValidationException::withMessages([
                'local_ip' => [__('Select an IPv4 address currently assigned to an active interface on this server.')],
            ]);
        }
        if ($data['layout'] === 'direct' && ! $this->publicIp($data['local_ip'])) {
            throw ValidationException::withMessages([
                'local_ip' => [__('For a direct public IP, select a public interface address. Otherwise choose Behind NAT or Private network.')],
            ]);
        }
        foreach ($data['layout'] === 'nat' ? ['public_ip', ...(! empty($data['separate_media']) ? ['media_ip'] : [])] : [] as $field) {
            if (! $this->publicIp($data[$field] ?? '')) {
                throw ValidationException::withMessages([
                    $field => [__('Enter a public IPv4 address. Use the variable editor for routed private or custom address configurations.')],
                ]);
            }
        }
        return $runtime;
    }

    private function rows(string $hostname, bool $lock = false): Collection
    {
        return SwitchVariable::query()->whereIn('var_name', self::NAMES)
            ->where(fn ($query) => $query->whereNull('var_category')->orWhere('var_category', '!=', 'Provision'))
            ->where(fn ($query) => $query->where('var_hostname', $hostname)->orWhereNull('var_hostname')->orWhere('var_hostname', ''))
            ->orderBy('var_uuid')->when($lock, fn ($query) => $query->lockForUpdate())->get();
    }

    private function review(array $data, string $hostname, Collection $rows): array
    {
        $values = [
            'local_ip_v4' => $data['local_ip'],
            'external_sip_ip' => $data['layout'] === 'nat' ? $data['public_ip'] : '$${local_ip_v4}',
            'external_rtp_ip' => $data['layout'] === 'nat'
                ? (! empty($data['separate_media']) ? $data['media_ip'] : $data['public_ip']) : '$${local_ip_v4}',
        ];
        $changes = [];
        foreach (self::NAMES as $order => $name) {
            $matches = $rows->where('var_name', $name);
            $specific = $matches->where('var_hostname', $hostname);
            $row = $specific->firstWhere('var_enabled', 'true') ?? $specific->first()
                ?? $matches->firstWhere('var_enabled', 'true') ?? $matches->first();
            $changes[] = [
                'id' => $row?->var_uuid, 'name' => $name, 'value' => $values[$name],
                'order' => $order * 10, 'hostname' => $hostname,
                'action' => $row ? 'update' : 'create', 'before' => $row?->only([
                    'var_value', 'var_hostname', 'var_enabled', 'var_command', 'var_category', 'var_order',
                ]),
            ];
            foreach ($matches as $duplicate) {
                if ($duplicate->var_uuid !== $row?->var_uuid && $duplicate->var_enabled === 'true') {
                    $changes[] = [
                        'id' => $duplicate->var_uuid, 'name' => $name, 'action' => 'disable',
                        'value' => $duplicate->var_value, 'order' => $duplicate->var_order,
                        'hostname' => $duplicate->var_hostname,
                        'before' => $duplicate->only(['var_value', 'var_hostname', 'var_enabled', 'var_command', 'var_category', 'var_order']),
                    ];
                }
            }
        }

        return [
            'hostname' => $hostname,
            'changes' => $changes,
            'shared_rows' => $rows->where('var_enabled', 'true')->filter(fn ($row) => blank($row->var_hostname))->count(),
            'review_token' => hash_hmac('sha256', json_encode([$hostname, $values, $rows->toArray()], JSON_THROW_ON_ERROR), (string) config('app.key')),
        ];
    }

    protected function runtime(): array
    {
        $esl = app(FreeswitchEslService::class);
        try {
            if (! $esl->isConnected()) {
                throw new \RuntimeException();
            }
            $hostname = $this->scalarResponse($esl->executeCommand('switchname', false));
            if ($hostname === null) {
                throw new \RuntimeException();
            }
            $values = [];
            foreach (self::NAMES as $name) {
                $values[$name] = $this->scalarResponse($esl->executeCommand('global_getvar '.$name, false));
            }
            return ['hostname' => $hostname, 'values' => $values];
        } catch (Throwable $exception) {
            throw ValidationException::withMessages([
                'runtime' => [__('Network Setup requires a running FreeSWITCH connection to identify this server. Restore the connection and retry.')],
            ]);
        } finally {
            $esl->disconnect();
        }
    }

    private function scalarResponse(mixed $value): ?string
    {
        $value = is_string($value) ? trim($value) : '';
        return $value !== '' && $value !== '_undef_' && ! str_starts_with($value, '-ERR') ? $value : null;
    }

    protected function interfaces(): array
    {
        try {
            $result = Process::timeout(5)->run(['ip', '-j', '-4', 'address', 'show']);
            if (! $result->successful()) {
                throw new \RuntimeException();
            }
            $interfaces = json_decode($result->output(), true, 512, JSON_THROW_ON_ERROR);
            $addresses = [];
            foreach ($interfaces as $interface) {
                if (! in_array('UP', $interface['flags'] ?? [], true) || in_array('LOOPBACK', $interface['flags'] ?? [], true)
                    || in_array($interface['operstate'] ?? '', ['DOWN', 'LOWERLAYERDOWN', 'NOTPRESENT'], true)) {
                    continue;
                }
                foreach ($interface['addr_info'] ?? [] as $address) {
                    $ip = $address['local'] ?? '';
                    if (($address['family'] ?? '') !== 'inet' || ($address['scope'] ?? '') !== 'global' || ! $this->unicastIp($ip)) {
                        continue;
                    }
                    $addresses[$ip] = ['address' => $ip, 'interface' => $interface['ifname'], 'label' => $ip.' ('.$interface['ifname'].')'];
                }
            }
            return array_values($addresses);
        } catch (Throwable $exception) {
            throw ValidationException::withMessages([
                'local_ip' => [__('Unable to read local network interfaces. Check that the ip command is available and retry.')],
            ]);
        }
    }

    private function unicastIp(string $ip): bool
    {
        if (! filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4)) {
            return false;
        }
        $parts = array_map('intval', explode('.', $ip));
        return $parts[0] > 0 && $parts[0] < 224 && $parts[0] !== 127 && ! ($parts[0] === 169 && $parts[1] === 254);
    }

    private function publicIp(string $ip): bool
    {
        if (! $this->unicastIp($ip) || ! filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4 | FILTER_FLAG_NO_PRIV_RANGE | FILTER_FLAG_NO_RES_RANGE)) {
            return false;
        }
        $parts = array_map('intval', explode('.', $ip));
        return ! ($parts[0] === 100 && $parts[1] >= 64 && $parts[1] <= 127);
    }
}
